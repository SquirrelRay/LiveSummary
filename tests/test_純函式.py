"""安全網測試：live_topics 的純函式——代表留言、找參考詞、加支線、加聊天、加參考詞、轉秒。"""
import live_topics as lt


def 新():
    return lt.新話題()


# ---------- 轉秒／秒轉字 ----------
def test_轉秒與秒轉字():
    assert lt.轉秒("[01:05] 字") == 65
    assert lt.轉秒("[1:01:05] 字") == 3665
    assert lt.轉秒("沒有時間") is None
    assert lt.秒轉字(65) == "01:05" and lt.秒轉字(3725) == "62:05"


# ---------- 代表留言 ----------
def test_三人以上重複的句子合併成一則():
    留言們 = [(10, "a", "草"), (11, "b", "草"), (12, "c", "草"), (13, "d", "其他話")]
    結果 = lt.代表留言(留言們)
    字們 = [字 for _, 字 in 結果]
    assert "[00:10] （3 人重複）草" in 字們
    assert "[00:13] d: 其他話" in 字們
    assert len(字們) == 2


def test_兩人重複不合併():
    結果 = lt.代表留言([(1, "a", "好"), (2, "b", "好")])
    assert [字 for _, 字 in 結果] == ["[00:01] a: 好", "[00:02] b: 好"]


def test_同一人重複不算多人():
    結果 = lt.代表留言([(1, "a", "好"), (2, "a", "好"), (3, "a", "好")])
    assert len(結果) == 3 and all("人重複" not in 字 for _, 字 in 結果)


def test_重複判斷不分大小寫與前後空白():
    結果 = lt.代表留言([(1, "a", "LUL"), (2, "b", " lul "), (3, "c", "Lul")])
    assert len(結果) == 1 and "3 人重複" in 結果[0][1]


def test_留言太多時平均挑且不超過上限():
    留言們 = [(i, f"u{i}", f"內容{i}") for i in range(100)]
    結果 = lt.代表留言(留言們)
    assert len(結果) == lt.MAX_CHAT_PER_CHECK
    秒們 = [s for s, _ in 結果]
    assert 秒們 == sorted(秒們) and 秒們[0] == 0 and 秒們[-1] > 80      # 不是只看開頭


def test_沒有留言回傳空():
    assert lt.代表留言([]) == []


# ---------- 找參考詞 ----------
def test_兩個不同的人輸入才算參考詞():
    詞 = lt.找參考詞([(1, "a", "爆雷"), (2, "b", "爆雷")])
    assert 詞 == ["爆雷"]
    assert lt.找參考詞([(1, "a", "爆雷"), (2, "a", "爆雷")]) == []      # 同一個人不算


def test_含常用字招呼語與提及的不算詞():
    留言們 = [(1, "a", "我的 安安 @小明 大家"), (2, "b", "我的 安安 @小明 大家")]
    assert lt.找參考詞(留言們) == []


def test_被更長且人數一樣的詞包住就只留長的():
    詞 = lt.找參考詞([(1, "a", "爆雷警告"), (2, "b", "爆雷警告")])
    assert 詞 == ["爆雷警告"]


def test_英文表情代碼不算():
    assert lt.找參考詞([(1, "a", "LUL KEKW"), (2, "b", "LUL KEKW")]) == []


def test_參考詞數量有上限():
    字們 = "甲乙丙丁庚辛壬癸子丑寅卯辰巳午申酉戌亥天地玄黃"
    留言們 = []
    for i in range(0, len(字們) - 1, 2):
        留言們 += [(i, "a", 字們[i:i + 2]), (i, "b", 字們[i:i + 2])]
    assert len(lt.找參考詞(留言們)) == lt.MAX_REF_WORDS


# ---------- 加支線 ----------
def test_加支線_太近的時間或相似的內容不重複():
    t = 新()
    lt.加支線(t, [(100, "提到新買的鍵盤"), (110, "完全不同的內容在這裡"), (200, "提到新買的鍵盤了")])
    assert t["支線"] == [(100, "提到新買的鍵盤")]        # 110 離 100 不到 30 秒；200 的內容太像


def test_加支線_間隔夠遠且內容不同就收():
    t = 新()
    lt.加支線(t, [(100, "甲甲甲甲"), (130, "乙乙乙乙")])
    assert [s for s, _ in t["支線"]] == [100, 130]       # 剛好差 30 秒不算太近


def test_加支線_最多保留五條且保留較早的():
    t = 新()
    lt.加支線(t, [(i * 100, f"支線{chr(65 + i)}{chr(97 + i) * 3}") for i in range(8)])
    assert len(t["支線"]) == lt.MAX_SIDE_PER_TOPIC
    assert [s for s, _ in t["支線"]] == [0, 100, 200, 300, 400]


# ---------- 加聊天／加參考詞 ----------
def test_加聊天_保留較新的():
    t = 新()
    lt.加聊天(t, [(i, f"留言{i}") for i in range(lt.MAX_CHAT_PER_TOPIC + 5)])
    assert len(t["聊天"]) == lt.MAX_CHAT_PER_TOPIC
    assert t["聊天"][-1][0] == lt.MAX_CHAT_PER_TOPIC + 4 and t["聊天"][0][0] == 5


def test_加參考詞_新的排前面且不重複且有上限():
    t = 新()
    lt.加參考詞(t, ["甲", "乙"])
    lt.加參考詞(t, ["丙", "甲"])
    assert t["參考詞"] == ["丙", "甲", "乙"]
    lt.加參考詞(t, [f"詞{i}" for i in range(20)])
    assert len(t["參考詞"]) == lt.MAX_REF_WORDS and t["參考詞"][0] == "詞0"
