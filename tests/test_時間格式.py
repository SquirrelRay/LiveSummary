# 時間格式單一來源 timefmt：邊界、加號、解析、補小時、幾分鐘前
import pytest

import live_topics as lt
import timefmt as tf
import transcribe


@pytest.mark.parametrize(("秒", "字"), [(0, "00:00"), (65, "01:05"), (3599, "59:59"), (3600, "1:00:00"),
                                      (3725, "1:02:05"), (36000 + 59, "10:00:59"), (-5, "00:00"), (59.9, "00:59")])
def test_秒轉字邊界(秒, 字):
    assert tf.秒轉字(秒) == 字


def test_加號與標記():
    assert tf.標記(754, 加號=True) == "[+12:34]"
    assert tf.標記(3725) == "[1:02:05]"
    assert tf.秒轉字(3600, 加號=True) == "+1:00:00"


@pytest.mark.parametrize(("行", "秒"), [("[59:59] 字", 3599), ("[1:00:00] 字", 3600), ("[1:02:05]", 3725),
                                      ("[75:12] 舊格式", 4512), ("[+12:34] 退回", 754), ("沒有時間", None)])
def test_轉秒(行, 秒):
    assert tf.轉秒(行) == 秒


def test_舊的兩套函式改走統一模組():
    for 秒 in (59, 3599, 3600, 3725):
        assert lt.秒轉字(秒) == tf.秒轉字(秒)
        assert transcribe.時間(秒) == tf.標記(秒)
    assert lt.時間標記 is tf.時間標記


def test_補小時():
    候選 = {5025, 5040, 5070}               # 1:23:45、1:24:00、1:24:30
    assert tf.補小時(1425, 候選) == 5025     # [23:45] 漏了小時 → 補回 1:23:45
    assert tf.補小時(5040, 候選) == 5040     # 本來就對
    assert tf.補小時(1426, 候選) == 1426     # 補一小時也對不上：原樣
    assert tf.補小時(9000, 候選) == 9000     # 比最小值大：不補
    assert tf.補小時(225, {7425}) == 7425    # 漏兩小時（2:03:45 寫成 03:45）
    assert tf.補小時(None, 候選) is None
    assert tf.補小時(10, set()) == 10


@pytest.mark.parametrize(("秒差", "字"), [(0, "剛剛"), (59, "剛剛"), (60, "1 分鐘前"), (3599, "59 分鐘前"),
                                        (3600, "1 小時前"), (3900, "1 小時 5 分鐘前"), (-3, "剛剛")])
def test_相對字(秒差, 字):
    assert tf.相對字(秒差) == 字


def test_換內文時間():
    文 = "- [75:12] 重點一\n- [01:05] 重點二 [+02:00]"
    assert tf.換內文時間(文, tf.秒轉字) == "- [1:15:12] 重點一\n- [01:05] 重點二 [02:00]"
