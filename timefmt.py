# 時間格式（單一來源）：秒數 ↔ 時間字、時間標記、「幾分鐘前」。純函式，只用標準函式庫，任何模組都能放心 import。
# 規則：未滿 1 小時 mm:ss（例如 05:12）、滿 1 小時一律 h:mm:ss（例如 1:15:12），不會出現 75:12。
# 「＋」前綴（例如 [+12:34]）：抓不到開播時間時，表示「從開始擷取起算」而不是直播實際進行時間。
import re

# 行首的時間標記：[mm:ss]、[h:mm:ss]、[+mm:ss]；分鐘欄不限兩位（舊格式 [75:12] 也讀得懂）
時間標記 = re.compile(r"^\[\+?(?:(\d+):)?(\d+):(\d+)\]")
# 文字中任何位置的時間標記（摘要內文裡的 [mm:ss]）
任意時間標記 = re.compile(r"\[\+?(?:(\d+):)?(\d+):(\d+)\]")


def 秒轉字(秒, 加號=False):
    """秒數 → 「05:12」或「1:15:12」；加號 = True 時前面加「+」。負數當 0。"""
    秒 = max(0, int(秒))
    h, m, s = 秒 // 3600, (秒 % 3600) // 60, 秒 % 60
    字 = f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"
    return ("+" if 加號 else "") + 字


def 標記(秒, 加號=False):
    """秒數 → 「[05:12]」「[1:15:12]」「[+12:34]」。"""
    return f"[{秒轉字(秒, 加號)}]"


def 組秒(h, m, s):
    return int(h or 0) * 3600 + int(m) * 60 + int(s)


def 轉秒(字):
    """行首的時間標記 → 秒數；沒有時間標記回傳 None。「+」前綴不影響秒數。"""
    m = 時間標記.match(字)
    return 組秒(*m.groups()) if m else None


def 補小時(秒, 候選們):
    """模型抄時間戳時可能漏掉小時（[1:23:45] 寫成 [23:45]）。
    秒數不在候選們裡、而且比候選們的最小值還小時，一次補一小時，剛好對上候選就用補回的值；對不上就原樣回傳。"""
    候選們 = {c for c in 候選們 if c is not None}
    if 秒 is None or not 候選們 or 秒 in 候選們 or 秒 >= min(候選們):
        return 秒
    補 = 秒 + 3600
    while 補 <= max(候選們):
        if 補 in 候選們:
            return 補
        補 += 3600
    return 秒


def 相對字(秒差):
    """距離現在多久 → 「剛剛」「3 分鐘前」「1 小時前」「1 小時 5 分鐘前」（以分鐘為單位，未滿 1 分鐘算剛剛）。"""
    分 = max(0, int(秒差)) // 60
    if 分 < 1:
        return "剛剛"
    if 分 < 60:
        return f"{分} 分鐘前"
    h, m = divmod(分, 60)
    return f"{h} 小時前" if m == 0 else f"{h} 小時 {m} 分鐘前"


def 換內文時間(文字, 換算):
    """把文字裡每個 [時間] 交給 換算(秒) 改寫（例如統一成 h:mm:ss）。換算回傳新的時間字（不含括號）。"""
    return 任意時間標記.sub(lambda m: f"[{換算(組秒(*m.groups()))}]", 文字)
