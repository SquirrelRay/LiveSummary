#   換話題判斷    live_topics.py  每 check_minutes 分鐘一次；同一次回答也產生支線；聊天室留言與參考詞也塞在這次呼叫裡（不另外呼叫）；一定會跑
#   分鐘摘要      live_topics.py  不是獨立呼叫：加在換話題判斷同一次呼叫裡（多一段提示與多一段輸出）；minute_summary 關掉就沒有這一項
