# 摘要類 token 的估算方式（常數都在下面，不是量測值的地方都有註明）：
#   提示詞字數：用 live_topics／summarize 目前的提示詞實際數出來（2026-10-13）。
#   文字稿密度、話題頻率：統計專案資料夾裡 300 分鐘已存的直播稿（每分鐘 221 字、每小時 5.4 個話題）。
#   每字 token 數與輸出 token：用思考比較.md 裡唯一一筆實際紀錄（migi_tw，中文、文字稿模式、思考關、11 分鐘：
#   輸入 25,014／輸出 4,765 token，共 11 次呼叫）校正；只有這一筆，所以判斷與分鐘摘要同一次呼叫的輸出是依比例拆開的。
#   延伸思考開啟時，輸出約為 3.7 倍（同一筆紀錄思考開 17,641 對思考關 4,765），輸入幾乎不變。
#   聊天室留言量隨聊天室熱度差很多，這裡只算一個中等量；實際用量請看狀態列的呼叫次數與費用。
import subtitle_speed

每字token = 0.75            # 中日文每字約 0.75 token（用上面那筆紀錄校正）
每分鐘字數 = 220            # 一般直播稿每分鐘字數（含時間戳記）
每行字數 = 50               # 判斷時帶入「最後 10 行」，一行約幾字
話題數每小時 = 5.4          # 一般直播每小時切出幾個話題
思考輸出倍數 = 3.7          # summary_thinking 開啟時摘要輸出的倍數

判斷固定字 = 556            # 換話題判斷的固定提示詞字數（不含分鐘摘要段）
分鐘規則字 = 489            # 分鐘摘要多出來的提示詞字數
外語說明字 = 286            # 外語直播多出來的「外語說明」字數（判斷與話題摘要都會加）
話題固定字 = 407            # 話題摘要的固定提示詞字數
簡述字 = 60                 # 「目前話題簡述」
最後行字 = 10 * 每行字數    # 判斷帶入的最後 10 行
聊天判斷字 = 350            # 聊天室開啟時，每次判斷多帶的留言（最多 15 則）與規則字數
聊天話題字 = 900            # 聊天室開啟時，話題摘要多帶的留言（最多 30 則）字數
判斷輸出 = 190              # 判斷＋簡述＋支線的輸出 token
分鐘輸出每句 = 90           # 分鐘摘要每句的輸出 token
分鐘輸出固定 = 60           # 分鐘摘要的觀眾反應與格式
話題輸出 = 450              # 一則話題摘要的輸出 token


摘要鍵們 = ("判斷", "分鐘", "話題")        # 合併成「摘要」的三項
備註們 = ["中文直播不需要翻譯，字幕翻譯為 $0", "金額依目前單價估算，實際以 API 帳單為準"]     # 費用表下方的兩行註明


def 金額(x):
    """表格裡的金額：$0.19。"""
    return f"${x:.2f}"


def _取整(x):
    return round(x + 1e-9, 2)


def 摘要用量(設定, 分鐘, 每分鐘字=每分鐘字數, 話題數=None):
    """這段時間（分鐘）摘要類呼叫的 token。回傳 {"判斷": (輸入, 輸出), "分鐘": (輸入, 輸出), "話題": (輸入, 輸出)}，
    分鐘摘要關閉時 "分鐘" 是 (0, 0)。話題數不給就用一般頻率。"""
    外語 = 設定["language"] != "zh"
    聊天 = bool(設定["chat"])
    次 = 分鐘 / 設定["check_minutes"]
    話題數 = 分鐘 / 60 * 話題數每小時 if 話題數 is None else 話題數
    倍 = 思考輸出倍數 if 設定["summary_thinking"] else 1.0

    判斷字 = (判斷固定字 + 簡述字 + 最後行字 + 設定["check_minutes"] * 每分鐘字
            + (外語說明字 if 外語 else 0) + (聊天判斷字 if 聊天 else 0))
    判斷 = (次 * 判斷字 * 每字token, 次 * 判斷輸出 * 倍)

    分鐘用量 = (0.0, 0.0)
    if 設定["minute_summary"]:
        輸出 = 分鐘輸出固定 + 分鐘輸出每句 * 設定["minute_sentences"]
        分鐘用量 = (次 * 分鐘規則字 * 每字token, 次 * 輸出 * 倍)

    話題字 = (話題數 * (話題固定字 + (外語說明字 if 外語 else 0) + (聊天話題字 if 聊天 else 0))
            + 分鐘 * 每分鐘字)               # 每個話題的文字稿，合起來就是整段文字稿
    話題 = (話題字 * 每字token, 話題數 * 話題輸出 * 倍)
    return {"判斷": 判斷, "分鐘": 分鐘用量, "話題": 話題}


def 翻譯狀態(設定, 翻譯面板開著):
    """回傳 (會不會翻譯, 狀態文字)。設定：載入設定() 的格式。"""
    模式, 語言 = 設定["subtitle_mode"], 設定["language"]
    if 模式 == "original" or (模式 == "auto" and 語言 == "zh"):
        return False, "未開啟（原文模式，中文直播不翻譯）"
    if not 翻譯面板開著:
        return False, "未開啟（逐句翻譯面板沒開）"
    return True, "開啟"


def _費用(用量, 設定):
    return 用量[0] / 1e6 * 設定["price_input"] + 用量[1] / 1e6 * 設定["price_output"]


def 估算(設定, 段位代碼, 翻譯面板開著):
    """回傳 {"項目們": [...], "合計": 美元, "備註": [...]}。
    設定：載入設定() 的格式（取單價、語言、字幕模式、摘要開關…），段位代碼：subtitle_speed 的代碼，
    翻譯面板開著：逐句翻譯面板是否開著（沒開就不翻譯）。
    每個項目：鍵、名稱、每小時（美元；沒開 = 0）、受段位影響、開啟、狀態、說明。合計是各項「顯示金額」的總和。"""
    摘要 = 摘要用量(設定, 60)
    開翻譯, 翻譯字 = 翻譯狀態(設定, 翻譯面板開著)
    分鐘開 = bool(設定["minute_summary"])
    n = 設定["check_minutes"]
    判斷名 = "話題追蹤（每分鐘檢查）" if n == 1 else f"話題追蹤（每 {n:g} 分鐘檢查）"
    項目們 = [
        {"鍵": "翻譯", "名稱": "字幕翻譯", "受段位影響": True, "開啟": 開翻譯, "狀態": 翻譯字,
         "每小時": _費用(subtitle_speed.每小時翻譯用量(段位代碼), 設定) if 開翻譯 else 0.0,
         "說明": "外語直播逐句翻成繁體中文；開逐句翻譯面板才翻"},
        {"鍵": "判斷", "名稱": 判斷名, "受段位影響": False, "開啟": True, "狀態": "開啟（固定）",
         "每小時": _費用(摘要["判斷"], 設定),
         "說明": "每次檢查一次，含支線、聊天室留言與參考詞"},
        {"鍵": "分鐘", "名稱": "分鐘摘要", "受段位影響": False, "開啟": 分鐘開,
         "狀態": "開啟" if 分鐘開 else "未開啟（設定裡關閉了分鐘摘要）",
         "每小時": _費用(摘要["分鐘"], 設定) if 分鐘開 else 0.0,
         "說明": "加在話題追蹤同一次呼叫裡的額外費用"},
        {"鍵": "話題", "名稱": "話題摘要", "受段位影響": False, "開啟": True, "狀態": "開啟（固定）",
         "每小時": _費用(摘要["話題"], 設定),
         "說明": "每個話題結束一次，輸入是整個話題的文字稿"},
    ]
    for 項 in 項目們:
        項["每小時"] = _取整(項["每小時"])
    合計 = _取整(sum(項["每小時"] for 項 in 項目們))
    return {"項目們": 項目們, "合計": 合計,
            "備註": list(備註們)}


def 項目金額字(項):
    return f"{金額(項['每小時'])}" if 項["開啟"] else "未開啟 $0"


def 合計字(結果):
    return f"US${結果['合計']:.2f}"


def _摘要合計(結果):
    return _取整(sum(x["每小時"] for x in 結果["項目們"] if x["鍵"] in 摘要鍵們))


def 總費用字(結果):
    """啟動面板按鈕列左邊：每小時約 US$0.46（估算）。字幕翻譯沒開時只算摘要。"""
    return f"每小時約 {合計字(結果)}（估算）"


比較表標題 = ("段位", "字幕延遲", "準確度", "每小時（估算）")


def 比較表列們(設定, 目前代碼, 翻譯面板開著):
    """啟動面板資訊圖示的三段位比較表。每列：代碼、名稱、延遲、準確度、合計、摘要、翻譯（沒開 = 未開啟 $0）、目前（是否選中）。"""
    列們 = []
    for 代碼 in subtitle_speed.代碼們:
        p = subtitle_speed.取得(代碼)
        結果 = 估算(設定, 代碼, 翻譯面板開著)
        翻譯 = next(x for x in 結果["項目們"] if x["鍵"] == "翻譯")
        列們.append({"代碼": 代碼, "名稱": p["名稱"], "延遲": f"約慢 {p['延遲秒']} 秒", "準確度": p["準確度說明"],
                   "合計": 合計字(結果), "摘要": 金額(_摘要合計(結果)), "翻譯": 項目金額字(翻譯), "目前": 代碼 == 目前代碼})
    return 列們


def 表格列們(結果):
    """設定框費用表每一列：項目／每小時（估算）／受字幕段位影響／目前狀態。摘要是小計列，三個細項縮排在它下面。"""
    項 = {x["鍵"]: x for x in 結果["項目們"]}

    def 列(x, 縮排=False):
        return (("　" if 縮排 else "") + x["名稱"], 項目金額字(x), "是" if x["受段位影響"] else "否", x["狀態"])
    列們 = [("項目", "每小時（估算）", "受字幕段位影響", "目前狀態"), 列(項["翻譯"]),
          ("摘要（小計）", 金額(_摘要合計(結果)), "否", "開啟")]
    列們 += [列(項[k], True) for k in 摘要鍵們]
    列們.append(("合計", 合計字(結果), "", ""))
    return 列們
