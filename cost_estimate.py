def 金額(x):
    """表格裡的金額：$0.19；None = 單價未知。"""
    return 未知字 if x is None else f"${x:.2f}"


def _取整(x):
    return None if x is None else round(x + 1e-9, 2)


def 摘要用量(設定, 分鐘, 每分鐘字=每分鐘字數, 話題數=None):
    """這段時間（分鐘）摘要類呼叫的 token。回傳 {"判斷": (輸入, 輸出), "分鐘": (輸入, 輸出), "話題": (輸入, 輸出)}，
    分鐘摘要關閉時 "分鐘" 是 (0, 0)。話題數不給就用一般頻率。"""
    外語 = 設定["language"] != "zh"
    聊天 = bool(設定["chat"])
    次 = 分鐘 / 設定["check_minutes"]
    話題數 = 分鐘 / 60 * 話題數每小時 if 話題數 is None else 話題數
    倍 = 思考輸出倍數 if 設定["summary_thinking"] else 1.0

    判斷字 = (判斷固定字 + 簡述字 + 最後行字 + 設定["check_minutes"] * 每分鐘字
            + (外語說明字 if 外語 else 0) + (聊天判斷字 if 聊天 else 0))
    判斷 = (次 * 判斷字 * 每字token, 次 * 判斷輸出 * 倍)

    分鐘用量 = (0.0, 0.0)
    if 設定["minute_summary"]:
        輸出 = 分鐘輸出固定 + 分鐘輸出每句 * 設定["minute_sentences"]
        分鐘用量 = (次 * 分鐘規則字 * 每字token, 次 * 輸出 * 倍)

    話題字 = (話題數 * (話題固定字 + (外語說明字 if 外語 else 0) + (聊天話題字 if 聊天 else 0))
            + 分鐘 * 每分鐘字)               # 每個話題的文字稿，合起來就是整段文字稿
    話題 = (話題字 * 每字token, 話題數 * 話題輸出 * 倍)
    return {"判斷": 判斷, "分鐘": 分鐘用量, "話題": 話題}


def 翻譯狀態(設定, 翻譯面板開著):
    """回傳 (會不會翻譯, 狀態文字)。設定：載入設定() 的格式。"""
    模式, 語言 = 設定["subtitle_mode"], 設定["language"]
    if 模式 == "original" or (模式 == "auto" and 語言 == "zh"):
        return False, "未開啟（原文模式，中文直播不翻譯）"
    if not 翻譯面板開著:
        return False, "未開啟（逐句翻譯面板沒開）"
    return True, "開啟"


def 聊天翻譯用量(每分上限, 量="中等"):
    """每小時聊天室翻譯的 (輸入 token, 輸出 token)。量："中等"（一般估算）或 "熱門"（每分鐘上限封頂）。"""
    q = 聊天量們[量]
    則 = min(q["每分則"], 每分上限) * 60
    輸入 = q["呼叫"] * 聊天固定輸入 + 則 * (聊天每則額外 + q["字"])
    輸出 = q["呼叫"] * 聊天固定輸出 + 則 * (聊天每則額外 + q["字"] * 聊天輸出每字)
    return 輸入, 輸出


def 查證狀態(設定):
    """回傳 (會不會上網查證, 狀態文字)。"""
    if not 設定.get("web_verify"):
        return False, "未開啟（設定裡關閉了上網查證）"
    if not model_catalog.支援上網查證(設定):
        return False, "未開啟（目前的模型服務不支援上網搜尋）"
    return True, "開啟"


def 查證每小時(設定):
    """每小時上網查證的 (token 費, 搜尋費)，美元；單價未知時 token 費是 None。"""
    token = _費用((查證每小時名詞 * 查證每詞輸入, 查證每小時名詞 * 查證每詞輸出), 設定)
    return token, 查證每小時名詞 * 查證每詞搜尋 * llm.每次搜尋美元


def 聊天翻譯狀態(設定, 聊天面板開著):
    """回傳 (會不會翻譯聊天室, 狀態文字)。"""
    if not 設定["chat_translate"]:
        return False, "未開啟（設定裡關閉了聊天室翻譯）"
    if not 設定["chat"]:
        return False, "未開啟（沒有抓聊天室）"
    if 設定["language"] == "zh":
        return False, "未開啟（中文直播不翻譯）"
    if not 聊天面板開著:
        return False, "未開啟（聊天室面板沒開）"
    return True, "開啟"


def 聊天備註(設定):
    """設定框費用表下方的一行：熱門台有每分鐘上限封頂（金額依目前單價與上限算）。"""
    熱門 = _費用(聊天翻譯用量(設定["chat_translate_max_per_min"], "熱門"), 設定)
    if 熱門 is None:
        return f"聊天室翻譯以中等聊天量估算；熱門台有每分鐘上限封頂（{未知字}）"
    return f"聊天室翻譯以中等聊天量估算；熱門台有每分鐘上限封頂，約 {金額(熱門)}／小時（估算）"


def _費用(用量, 設定):
    """用量 (輸入 token, 輸出 token) 的美元；單價未知回傳 None。"""
    單價 = model_catalog.單價(設定)
    if 單價 is None:
        return None
    return 用量[0] / 1e6 * 單價[0] + 用量[1] / 1e6 * 單價[1]


def _加總(值們):
    值們 = list(值們)
    return None if any(v is None for v in 值們) else sum(值們)


def 估算(設定, 段位代碼, 翻譯面板開著, 聊天面板開著=False):
    """回傳 {"項目們": [...], "合計": 美元, "備註": [...]}。
    設定：載入設定() 的格式（取單價、語言、字幕模式、摘要開關…），段位代碼：subtitle_speed 的代碼，
    翻譯面板開著：逐句翻譯面板是否開著（沒開就不翻譯）；聊天面板開著：聊天室面板是否開著（聊天室翻譯要它開著）。
    每個項目：鍵、名稱、每小時（美元；沒開 = 0）、受段位影響、開啟、狀態、說明。合計是各項「顯示金額」的總和。"""
    摘要 = 摘要用量(設定, 60)
