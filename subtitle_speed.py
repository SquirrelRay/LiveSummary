# 字幕速度段位（config.json 的 subtitle_speed）：在「字幕出得快」與「轉錄比較準、翻譯比較省」之間選一個。
# 段位決定音訊分段秒數與翻譯批次（舊的 translate_batch_seconds／translate_batch_lines 已停用、讀入時忽略）。
# 一律「下次開始生效」：直播中不切換（分段長度在擷取迴圈裡固定，中途改會讓時間戳錯位）。
# 延遲與準確度的說明文字、每小時翻譯 token 數都只放在這裡；費用金額由 cost_estimate.py 依目前單價算出。
# 翻譯字幕延遲來自 2026-10-12 第一階段量測（RTX 4070 Laptop、large-v3-turbo，日文遊戲直播 10 分鐘錄音；翻譯為模擬、沒有呼叫 API）；
# 每小時翻譯 token 為同次模擬值。

預設 = "balanced"

段位們 = {
    "fast":     {"名稱": "速度", "分段秒": 8,  "批次秒": 1, "批次句": 8, "每小時輸入": 165_000, "每小時輸出": 15_000,
                 "延遲秒": 8,  "延遲說明": "延遲最短（翻譯字幕約慢 8 秒）", "準確度說明": "偶爾斷句、錯字"},
    "balanced": {"名稱": "平衡", "分段秒": 12, "批次秒": 1, "批次句": 8, "每小時輸入": 118_000, "每小時輸出": 15_000,
                 "延遲秒": 11, "延遲說明": "延遲中等（翻譯字幕約慢 11 秒）", "準確度說明": "準確度佳（建議）"},
    "accurate": {"名稱": "準度", "分段秒": 20, "批次秒": 8, "批次句": 8, "每小時輸入": 84_000,  "每小時輸出": 14_000,
                 "延遲秒": 18, "延遲說明": "延遲較長（翻譯字幕約慢 18 秒）", "準確度說明": "最準、最省錢"},
}
代碼們 = tuple(段位們)          # 顯示順序：速度、平衡、準度


def 合法(代碼):
    return isinstance(代碼, str) and 代碼 in 段位們


def 取得(代碼):
    """回傳段位的設定（dict）；不認得的代碼用預設段位。"""
    return 段位們[代碼] if 合法(代碼) else 段位們[預設]


def 每小時翻譯用量(代碼):
    """回傳 (輸入 token, 輸出 token)：這個段位翻譯一小時外語直播的模擬用量。"""
    p = 取得(代碼)
    return p["每小時輸入"], p["每小時輸出"]


def 延遲準確度字(代碼):
    """例：延遲中等（翻譯字幕約慢 11 秒）・準確度佳（建議）。啟動面板第一行與設定框共用。"""
    p = 取得(代碼)
    return f"{p['延遲說明']}・{p['準確度說明']}"


def 批次文字(代碼):
    p = 取得(代碼)
    return f"分段 {p['分段秒']} 秒；翻譯批次：最多等 {p['批次秒']} 秒或累積 {p['批次句']} 句"


def 簡短說明(代碼):
    """啟動面板按鈕的滑鼠提示。"""
    return 延遲準確度字(代碼) + "\n" + 批次文字(代碼)


def 里程碑說明(代碼):
    """啟動里程碑紀錄開頭要寫的段位資訊。"""
    p = 取得(代碼)
    return {"字幕速度段位": f"{p['名稱']}（{代碼 if 合法(代碼) else 預設}）", "分段長度設定(秒)": p["分段秒"],
            "翻譯批次秒數": p["批次秒"], "翻譯批次句數": p["批次句"]}
