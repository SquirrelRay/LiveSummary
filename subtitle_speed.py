# 字幕速度段位（config.json 的 subtitle_speed）：在「字幕出得快」與「轉錄比較準、翻譯比較省」之間選一個。
# 段位決定音訊分段秒數與翻譯批次（舊的 translate_batch_seconds／translate_batch_lines 已停用、讀入時忽略）。
# 一律「下次開始生效」：直播中不切換（分段長度在擷取迴圈裡固定，中途改會讓時間戳錯位）。
# 估算數字來自 2026-10-12 的實測（RTX 4070 Laptop、large-v3-turbo，日文遊戲直播 10 分鐘錄音；翻譯為模擬、沒有呼叫 API）：
#   第一句 ≈ 啟動約 7.5 秒 + 分段秒數 + 串流與轉錄約 1.7 秒；翻譯模式再加 API 約 4 秒
#   每小時翻譯 token 為模擬值，費用 = token × config.json 的單價（單價本身也未查證）

預設 = "balanced"

段位們 = {
    "fast":     {"名稱": "速度", "分段秒": 8,  "批次秒": 1, "批次句": 8, "每小時輸入": 165_000, "每小時輸出": 15_000},
    "balanced": {"名稱": "平衡", "分段秒": 12, "批次秒": 1, "批次句": 8, "每小時輸入": 118_000, "每小時輸出": 15_000},
    "accurate": {"名稱": "準度", "分段秒": 20, "批次秒": 8, "批次句": 8, "每小時輸入": 84_000,  "每小時輸出": 14_000},
}
代碼們 = tuple(段位們)          # 顯示順序：速度、平衡、準度

_啟動秒 = 9.2                  # 按開始到第一段送轉錄之前、扣掉分段秒數的部分（含轉錄）
_翻譯秒 = 4.0                  # 第一批翻譯 API 來回


def 合法(代碼):
    return isinstance(代碼, str) and 代碼 in 段位們


def 取得(代碼):
    """回傳段位的設定（dict）；不認得的代碼用預設段位。"""
    return 段位們[代碼] if 合法(代碼) else 段位們[預設]


def 估算第一句(代碼):
    """回傳 (原文模式秒數, 翻譯模式秒數)，四捨五入到整數。第一段沒人聲時會再多等一段。"""
    n = 取得(代碼)["分段秒"]
    return round(_啟動秒 + n), round(_啟動秒 + n + _翻譯秒)


def 估算每小時翻譯費用(代碼, 單價輸入, 單價輸出):
    """每小時翻譯費用（美元，估算）。單價：每百萬 token 美元。"""
    p = 取得(代碼)
    return p["每小時輸入"] / 1e6 * 單價輸入 + p["每小時輸出"] / 1e6 * 單價輸出


def 批次文字(代碼):
    p = 取得(代碼)
    return f"分段 {p['分段秒']} 秒；翻譯批次：最多等 {p['批次秒']} 秒或累積 {p['批次句']} 句"


def 簡短說明(代碼):
    """啟動面板按鈕的滑鼠提示。"""
    原, 譯 = 估算第一句(代碼)
    return f"{批次文字(代碼)}\n估算第一句出現：中文原文約 {原} 秒、外語翻譯約 {譯} 秒"


def 詳細說明(代碼, 單價輸入, 單價輸出):
    """設定框裡段位下方的說明。費用一律標示「估算」。"""
    原, 譯 = 估算第一句(代碼)
    費 = 估算每小時翻譯費用(代碼, 單價輸入, 單價輸出)
    return (f"{批次文字(代碼)}\n"
            f"估算第一句出現：中文原文約 {原} 秒、外語翻譯約 {譯} 秒（第一段沒人聲會再多等一段）\n"
            f"估算每小時翻譯費用：約 ${費:.2f}（依 config.json 單價、以日文直播實測句數模擬；中文直播用原文不花翻譯費）")


def 里程碑說明(代碼):
    """啟動里程碑紀錄開頭要寫的段位資訊。"""
    p = 取得(代碼)
    return {"字幕速度段位": f"{p['名稱']}（{代碼 if 合法(代碼) else 預設}）", "分段長度設定(秒)": p["分段秒"],
            "翻譯批次秒數": p["批次秒"], "翻譯批次句數": p["批次句"]}
