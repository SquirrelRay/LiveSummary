# 事件機制：引擎不直接 print，而是「送出事件」，由接收者決定怎麼顯示
# 接收者 = 一個函式 (種類, 內容)。終端機用 印到終端機；介面（app.py）是另一個接收者。
# 每個事件的「印出」欄位 = 以前命令列會印的那段文字（沒有就代表命令列本來不印）。
#
# 事件種類與內容：
#   transcript_line  逐句轉錄：秒、時間字、內容（不含時間）、行（含 [mm:ss] 的原始行）
#   chat_line        聊天室留言：秒、時間字、使用者、內容、編號（新留言編號()，給聊天室翻譯補譯文用）
#                    聊天室翻譯開著時，聊天室翻譯器（排在介面前面的接收者）會在內容加 暫留=True：介面先不顯示，等 chat_show
#   chat_show        聊天室翻譯開著時要顯示的留言（照原本順序）：編號、時間字、使用者、內容、譯文（None = 只顯示原文）
#   chat_status      YouTube 聊天室狀態（Twitch 不送）：狀態（已連上／沒有聊天室／失效）、說明（聊天室面板顯示的一行）、
#                    印出；沒有聊天室與失效另有 膠囊（膠囊旁也提示）
#   minute_summary   分鐘摘要：秒、摘要、支線（[(秒, 文字)]）、觀眾反應、印出
#   topic_summary    話題摘要：開始、結束（mm:ss）、內文、印出
#   current_topic    目前話題：秒、簡述、進行分鐘、印出
#   status           狀態（只放有變的欄位）：跟上（True/False）、次數、輸入、輸出、費用（None = 無法計算）
#   stream_info      直播資訊：有開播、連續、開播、延遲、來源、平台、直播主、標題、遊戲、印出
#   stream_sync      YouTube 時間對齊完成：對齊（片段時間戳／估計）、延遲（這次實際的串流延遲，或估計值）
#   info             一般提示訊息：印出
#   error            錯誤：訊息（給對話框）、印出
#   stage            啟動階段（給啟動面板顯示「啟動中…」的階段文字）：階段
#   language_detected 語言偵測結果：語言（失敗時是實際使用的語言）、信心、狀態（ok／低信心／失敗）、重新偵測（True = 重新偵測）
#   wrapup           按停止後的收尾階段（給介面顯示「正在整理最後的話題摘要…」）：階段（話題摘要／上網查證）、上限（秒）
#   finished         結束：話題數、檔案們、未完成（收尾超過時間上限而沒完成的項目，沒有就是空清單）、印出
import itertools
import threading

接收者們 = []
_留言編號 = itertools.count(1)
停止 = threading.Event()   # 介面按「停止」時設起來，效果等同 Ctrl+C
放棄收尾 = threading.Event()   # 收尾中使用者確定要直接結束程式：不再等最後的話題摘要與上網查證（已有的照樣存檔）
重新偵測 = threading.Event()   # 介面按「重新偵測」時設起來；引擎在下一段音訊重新判斷語言（不中斷串流）


def 新留言編號():
    """每則聊天室留言一個不重複的編號（整個程式共用，跨場次也不重複）。"""
    return next(_留言編號)


def 送出(種類, **內容):
    for 接收 in list(接收者們):
        try:
            接收(種類, 內容)
        except Exception:
            pass     # 接收者出錯不能讓引擎停掉


def 印到終端機(種類, 內容):
    """命令列用的接收者：照以前的樣子印出來。"""
    文字 = 內容.get("印出")
    if 文字 is not None:
        print(文字)
